// `no_top` 的夹具：**一个模块都没有的文件**。
//
// 这不是"设计有问题"，是"没什么可综合的"。触发它最常见的三种情形：
//
//   1. 文件是空的（或者只有注释和宏定义，就像本文件）
//   2. 路径写错了，synth.py 拿到的是一个根本不存在的文件
//   3. 模块全在别的文件里，而这次没一起传进来（缺 `-I` 或漏了文件名）
//
// iverilog 的原话是 `error: No top level modules, and no -s option.` ——
// 注意它把"No top level modules"和"没给 -s"并列了，所以**给了 -s 也可能报这句**
// （-s 指的模块不存在时一样没有顶层）。
//
// 单独分一类而不是并进 compile_error：它退出码也是 1、也没写出文件，
// 和"语法错"在下游长得一样，但要做的事完全不同 ——
// 语法错去改代码，这个去检查传了哪些文件。
